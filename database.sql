CREATE DATABASE IF NOT EXISTS virtual_classroom CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE virtual_classroom;
CREATE TABLE admin(id INT AUTO_INCREMENT PRIMARY KEY,username VARCHAR(80) NOT NULL UNIQUE,password VARCHAR(255) NOT NULL);
CREATE TABLE student(id INT AUTO_INCREMENT PRIMARY KEY,roll_no VARCHAR(80) NOT NULL UNIQUE,name VARCHAR(150) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,password VARCHAR(255) NOT NULL,degree VARCHAR(150) NOT NULL,is_approved TINYINT(1) NOT NULL DEFAULT 0,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE faculty(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,subject VARCHAR(150) NOT NULL,password VARCHAR(255) NOT NULL,is_approved TINYINT(1) NOT NULL DEFAULT 0,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE enroll_for(id INT AUTO_INCREMENT PRIMARY KEY,student_id INT NOT NULL,faculty_id INT NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(student_id) REFERENCES student(id) ON DELETE CASCADE,FOREIGN KEY(faculty_id) REFERENCES faculty(id) ON DELETE CASCADE);


-- Classroom content modules
CREATE TABLE IF NOT EXISTS video_lectures (
 id INT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 description TEXT NULL,
 subject VARCHAR(150) NOT NULL,
 video_type ENUM('upload','url') NOT NULL DEFAULT 'upload',
 video_path VARCHAR(255) NULL,
 video_url VARCHAR(1000) NULL,
 faculty_id INT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS study_materials (
 id INT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 description TEXT NULL,
 subject VARCHAR(150) NOT NULL,
 file_path VARCHAR(255) NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 faculty_id INT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS questions (
 id INT AUTO_INCREMENT PRIMARY KEY,
 student_id INT NOT NULL,
 subject VARCHAR(150) NOT NULL,
 question TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS answers (
 id INT AUTO_INCREMENT PRIMARY KEY,
 question_id INT NOT NULL,
 faculty_id INT NULL,
 admin_id INT NULL,
 answer TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE,
 FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE SET NULL,
 FOREIGN KEY (admin_id) REFERENCES admin(id) ON DELETE SET NULL
);
